"use strict";
var assert = require("assert"), fs = require("fs"), vm = require("vm");
var ctx = { console: console, Math: Math };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync("web/js/v13-knowledge.js", "utf8"), ctx, { filename: "v13-knowledge.js" });
var G = ctx.IGRA;
assert(G && G.V13Knowledge, "V13 knowledge layer loads");
var world = {};
var state = G.V13Knowledge.ensure(world);
assert(Array.isArray(state.discoveries), "discoveries collection exists");
var d = G.V13Knowledge.discover(world, "law:tide-follows-care", 0.72);
assert.strictEqual(d.id, "law:tide-follows-care", "discovery key is retained");
assert.strictEqual(d.evidence, 0.72, "evidence is bounded and retained");
var again = G.V13Knowledge.discover(world, "law:tide-follows-care", 0.99);
assert.strictEqual(world.knowledge.discoveries.length, 1, "duplicate discovery does not spam knowledge");
assert.strictEqual(again.evidence, 0.72, "existing evidence is stable");
G.V13Knowledge.discover(world, "law:scar-follows-harm", -1);
assert.strictEqual(world.knowledge.discoveries[0].evidence, 0, "negative evidence clamps to zero");
for (var i = 0; i < 80; i++) G.V13Knowledge.discover(world, "law:" + i, i / 80);
assert(world.knowledge.discoveries.length <= 64, "knowledge history is bounded");
var malformed = { knowledge: { discoveries: "bad", laws: null, interactions: [] } };
var normalized = G.V13Knowledge.ensure(malformed);
assert(Array.isArray(normalized.discoveries), "malformed discoveries are repaired");
assert(Array.isArray(normalized.laws), "malformed laws are repaired");
assert(Array.isArray(normalized.interactions), "valid interactions remain arrays");
console.log("V13 knowledge probe: PASS");
