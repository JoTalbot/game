"use strict";
var assert = require("assert"), fs = require("fs"), vm = require("vm");
var ctx = { console: console, Math: Math };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync("web/js/v18-experiments.js", "utf8"), ctx, { filename: "v18-experiments.js" });
var G = ctx.IGRA;
assert(G && G.V18Experiments, "V18 experiments layer loads");
var world = {};
var state = G.V18Experiments.ensure(world);
assert(Array.isArray(state.records) && state.records.length === 0, "fresh experiment state is empty");
var first = G.V18Experiments.record(world, "what follows care", "care", "bloom:r0");
assert(first && first.id === "x1", "first experiment receives stable local id");
assert.strictEqual(first.hypothesis, "what follows care", "hypothesis is preserved");
assert.strictEqual(first.action, "care", "action is preserved");
assert.strictEqual(first.outcome, "bloom:r0", "outcome is preserved");
for (var i = 0; i < 40; i++) G.V18Experiments.record(world, "h" + i, "a" + i, "o" + i);
assert(state.records.length === 32, "experiment history remains bounded");
assert(state.records[0].hypothesis === "h8", "oldest experiment is compacted first");
var malformed = { experiments: { records: "bad" } };
var repaired = G.V18Experiments.ensure(malformed);
assert(Array.isArray(repaired.records) && repaired.records.length === 0, "malformed experiment collection is repaired");
var long = "x".repeat(200);
var bounded = G.V18Experiments.record(malformed, long, long, long);
assert(bounded.hypothesis.length === 96 && bounded.action.length === 96 && bounded.outcome.length === 96, "experiment text is bounded");
console.log("V18 experiments probe: PASS");
