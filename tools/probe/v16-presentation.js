"use strict";
var assert = require("assert"), fs = require("fs"), vm = require("vm");
var ctx = { console: console, Math: Math };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync("web/js/v16-presentation.js", "utf8"), ctx, { filename: "v16-presentation.js" });
var G = ctx.IGRA;
assert(G && G.V16Presentation, "V16 presentation layer loads");
var world = {};
var fresh = G.V16Presentation.ensure(world);
assert.strictEqual(fresh.detail, 1, "fresh detail profile is full");
G.V16Presentation.budget(world, 2, 999, 999);
assert.strictEqual(world.presentationV16.detail, 1, "detail is capped");
assert.strictEqual(world.presentationV16.effects, 24, "effects budget is capped");
assert.strictEqual(world.presentationV16.floats, 8, "floater budget is capped");
G.V16Presentation.budget(world, -1, -5, -2);
assert.strictEqual(world.presentationV16.detail, 0.5, "detail has low-end floor");
assert.strictEqual(world.presentationV16.effects, 0, "negative effects clamp to zero");
assert.strictEqual(world.presentationV16.floats, 0, "negative floaters clamp to zero");
var malformed = { presentationV16: { detail: "bad", effects: "bad", floats: "bad" } };
var normalized = G.V16Presentation.ensure(malformed);
assert.strictEqual(normalized.detail, "bad", "ensure preserves state for budget normalization");
G.V16Presentation.budget(malformed, "bad", "bad", "bad");
assert(Number.isFinite(normalized.effects), "malformed effects become finite");
assert(Number.isFinite(normalized.floats), "malformed floaters become finite");
console.log("V16 presentation probe: PASS");
