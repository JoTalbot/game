"use strict";
var assert = require("assert"), fs = require("fs"), vm = require("vm");
var ctx = { console: console, Math: Math };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync("web/js/v17-adaptive-audio.js", "utf8"), ctx, { filename: "v17-adaptive-audio.js" });
var G = ctx.IGRA;
assert(G && G.V17AdaptiveAudio, "V17 adaptive audio layer loads");
var world = {};
var fresh = G.V17AdaptiveAudio.ensure(world);
assert.strictEqual(fresh.ambience, 0.5, "fresh ambience is bounded");
G.V17AdaptiveAudio.react(world, { intensity: 0.15, motif: "silence", silence: 0.9 });
assert.strictEqual(fresh.ambience, 0.15, "quiet context is applied");
assert.strictEqual(fresh.motif, "silence", "quiet motif is retained");
G.V17AdaptiveAudio.react(world, { intensity: 0.85, motif: "garden", silence: 0.1 });
assert.strictEqual(fresh.ambience, 0.85, "active ambience is applied");
assert.strictEqual(fresh.motif, "garden", "motif changes with context");
assert.strictEqual(fresh.silence, 0.1, "silence follows context");
G.V17AdaptiveAudio.react(world, { intensity: 9, motif: "storm", silence: -9 });
assert.strictEqual(fresh.ambience, 1, "ambience clamps high input");
assert.strictEqual(fresh.silence, 0, "silence clamps low input");
var malformed = { audioV17: { ambience: "bad", motif: null, silence: "bad" } };
var normalized = G.V17AdaptiveAudio.ensure(malformed);
G.V17AdaptiveAudio.react(malformed, { intensity: "bad", motif: "storm", silence: "bad" });
assert(Number.isFinite(normalized.ambience), "malformed ambience is repaired through reaction");
assert(Number.isFinite(normalized.silence), "malformed silence is repaired through reaction");
console.log("V17 adaptive audio probe: PASS");
